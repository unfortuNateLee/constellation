// Physics-parity harness — step 1 of 2 (graph input).
//
// Derives the exact node/edge set the D3 force simulation runs on from
// `fixtures/comprehensive.vcf`, using the REAL js/ RelationshipBuilder, and
// writes a minimal, physics-only projection to
// `macos/ConstellationKit/Tests/Goldens/physics/graph-input.json`.
//
// This isolates *physics* parity from *graph-model* parity (already proven by
// the M1 byte-parity gate): both the d3 ground-truth dump (dump-d3.cjs) and the
// Swift PhysicsParityTests consume this one JSON, so any divergence they find is
// purely in the force simulation, never in how the graph was built.
//
// Usage: node scripts/physics-parity/build-graph-input.mjs
//
// Lint note: this is `.mjs`, so the repo's node-globals block (scoped to
// scripts/**/*.js) does not apply; it is linted with eslint's recommended
// config only. Every Node API is therefore imported explicitly and
// process.stdout is used instead of the bare `console`.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

import { loadBrowserClasses, readFixture } from '../../test/helpers/load-app.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');
const outDir = path.join(repoRoot, 'macos', 'ConstellationKit', 'Tests', 'Goldens', 'physics');

// Build options are pinned here so the graph is reproducible bit-for-bit. Any
// change must be mirrored in the goldens (regenerate) and documented in README.
const BUILD_OPTIONS = {
  mode: 'connections',
  includeInferred: true,
  includeLikelyFamily: true,
  includeLikelyConnections: true,
  includeIsolated: true,
  includeVirtual: true,
  rootContactId: null,
};

const FIXTURE = 'comprehensive.vcf';

function main() {
  const ctx = loadBrowserClasses();
  const { VCardAdapter, RelationshipBuilder } = ctx;

  const contacts = new VCardAdapter().parse(readFixture(FIXTURE), {});
  const builder = new RelationshipBuilder(contacts);
  const data = builder.build(BUILD_OPTIONS);

  // Mirror graph.js `_renderGraph`: drop edges whose endpoints aren't nodes.
  const nodeIds = new Set(data.nodes.map((n) => n.id));
  const validEdges = data.edges.filter((e) => {
    const s = typeof e.source === 'object' ? e.source.id : e.source;
    const t = typeof e.target === 'object' ? e.target.id : e.target;
    return nodeIds.has(s) && nodeIds.has(t);
  });

  // Minimal physics-only projection. Node order and edge order are preserved
  // EXACTLY as the builder produced them — this order is load-bearing for LCG
  // (jiggle) stream alignment and Barnes-Hut accumulation order.
  const nodes = data.nodes.map((n) => ({
    id: n.id,
    isGroupNode: !!n.isGroupNode,
    groupDepth: n.groupDepth == null ? null : n.groupDepth,
    isCompany: !!n.isCompany,
    isVirtual: !!n.isVirtual,
    connectionCount: n.connectionCount | 0,
    category: n.category ?? 'other',
  }));

  const edges = validEdges.map((e) => ({
    id: e.id,
    source: typeof e.source === 'object' ? e.source.id : e.source,
    target: typeof e.target === 'object' ? e.target.id : e.target,
    edgeKind: e.edgeKind == null ? null : e.edgeKind,
    category: e.category ?? 'other',
  }));

  const out = {
    _comment:
      'Physics-parity graph input. Generated by scripts/physics-parity/build-graph-input.mjs ' +
      `from fixtures/${FIXTURE} via the js/ RelationshipBuilder. Node/edge ORDER is ` +
      'significant (LCG stream + Barnes-Hut). Regenerate with: node ' +
      'scripts/physics-parity/build-graph-input.mjs',
    fixture: FIXTURE,
    buildOptions: BUILD_OPTIONS,
    nodes,
    edges,
  };

  fs.mkdirSync(outDir, { recursive: true });
  const outPath = path.join(outDir, 'graph-input.json');
  fs.writeFileSync(outPath, `${JSON.stringify(out, null, 2)}\n`, 'utf8');
  process.stdout.write(
    `graph-input.json: ${nodes.length} nodes, ${edges.length} edges -> ${outPath}\n`,
  );
}

main();
