//   const contacts = new VCardAdapter().parse(readFixture("comprehensive.vcf"));
//   const builder = new RelationshipBuilder(contacts);
//
//   const c = (v) => (v === undefined || v === null || v === "" ? "-" : String(v));
//   const projEdges = (edges) => edges.map((e) =>
//     [c(e.source), c(e.target), c(e.type), c(e.label), c(e.reverseLabel),
//      c(e.category), c(e.inferred), c(e.edgeKind), c(e.confidence)].join("|")).sort();
//   const projNodes = (nodes) => nodes.map((n) =>
//     [c(n.id), c(n.category), c(n.isVirtual), c(n.isGroupNode),
//      (n.filterTags || []).join(",")].join("|")).sort();
//   const projHulls = (hulls) => hulls.map((h) =>
//     [c(h.id), c(h.kind), c(h.label), (h.memberIds || []).slice().sort().join(",")].join("|")).sort();
//
//   const conn = builder.build();
//   const geo = builder.build({ mode: "geographic" });
//   console.log(JSON.stringify({
//     connNodes: projNodes(conn.nodes), connEdges: projEdges(conn.edges), connHulls: projHulls(conn.hulls),
//     geoNodes: projNodes(geo.nodes), geoEdges: projEdges(geo.edges), geoHulls: projHulls(geo.hulls),
//     connStats: builder.getStats(conn.nodes, conn.edges),
//     geoStats: builder.getStats(geo.nodes, geo.edges),
//   }, null, 2));
//   '
//
// ── Options mirrored ─────────────────────────────────────────────────────
// Default connections: `builder.build()` — JS destructured defaults
// (mode: 'connections', includeInferred: true, includeLikelyFamily: true,
// includeLikelyConnections: true, includeIsolated: false, includeVirtual: true,
// rootContactId: null) — identical to `GraphBuildOptions()` on the Swift side.
// Geographic: `builder.build({ mode: 'geographic' })` — JS `_buildGeographic`
// only reads includeIsolated (default false) and rootContactId (default null,
// unused unless includeIsolated) — identical to `GraphBuildOptions(mode: .geographic)`.
//
// ── Projection format ────────────────────────────────────────────────────
//   node:  id|category|isVirtual|isGroupNode|filterTags.joined(",")
//   edge:  source|target|type|label|reverseLabel|category|inferred|edgeKind|confidence
//   hull:  id|kind|label|memberIds.sorted().joined(",")
// All lists sorted lexicographically before comparison, since neither side's
// edge/node emission order is part of the contract being verified here
// (RelationshipBuilderTests.determinismAcrossBuilds already covers ordering
// stability).
//
// ── Canonicalizations (both sides funnel through the same `c(_:)` helper) ──
//   • nil / undefined  → "-"   (JS: reverseLabel is `null` until a valid
//     reciprocal is found; edgeKind is omitted entirely on inferred org-
//     colleague edges; confidence is `undefined` on explicit/inferred-org
//     edges that never set it.)
//   • "" (empty string) → "-"  (JS emits label: '' for `contains` /
//     `located-at` geographic edges — no meaningful label exists yet the key
//     is always present; folding it into the same sentinel as "absent"
//     keeps the comparison about semantics — "is there a label" — not
//     about JS's undefined-vs-empty-string implementation detail.)
//   • Bool → "true"/"false" via Swift's `String(describing:)`, matching JS's
//     `String(true)` / `String(false)`.
//   • Double confidence → `String(Double)`, verified to match JS's
//     `String(Number)` for the two confidence constants in use (0.45, 0.38).
//
// Node/edge ids are stable hashes of the contact UID (ContactRecord.assignStableId
// / StableID.swift — both ports of the same FNV-1a/base36 algorithm), so the
// same fixture produces byte-identical ids on both sides; the sets below
// embed those hashed ids directly rather than re-deriving them per test.

private struct Fixture {
    let contacts: [Contact]

    init() {
        contacts = VCardAdapter().parse(FixtureLoader.contents(of: "comprehensive.vcf")).contacts
    }
}

// MARK: - Swift-side projection (mirrors the JS generator script above)

private func c(_ v: String?) -> String {
    guard let v, !v.isEmpty else { return "-" }
    return v
}

private func c(_ v: Bool) -> String { String(v) }

private func c(_ v: Double?) -> String {
    guard let v else { return "-" }
    return String(v)
}

private func projectNodes(_ nodes: [GraphNode]) -> [String] {
    nodes.map { n in
        [c(n.id), c(n.category), c(n.isVirtual), c(n.isGroupNode), c(n.filterTags.joined(separator: ","))]
            .joined(separator: "|")
    }.sorted()
}

private func projectEdges(_ edges: [GraphEdge]) -> [String] {
    edges.map { e in
        [
            c(e.source), c(e.target), c(e.type), c(e.label), c(e.reverseLabel),
            c(e.category), c(e.inferred), c(e.edgeKind), c(e.confidence),
        ].joined(separator: "|")
    }.sorted()
}

private func projectHulls(_ hulls: [GraphHull]) -> [String] {
    hulls.map { h in
        [c(h.id), c(h.kind), c(h.label), h.memberIds.sorted().joined(separator: ",")]
            .joined(separator: "|")
    }.sorted()
}

