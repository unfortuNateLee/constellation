// Deep fixture-driven verification of `RelationshipBuilder` against the real
// JS implementation (js/relationship-builder.js). Where RelationshipBuilderTests.swift
// asserts counts and a handful of spot-checked relationships, this file asserts
// EXACT SETS — every node, edge, and hull the builder produces — so any
// content-level divergence from the JS (a wrong label, a dropped filter tag, a
// mis-ordered member list) becomes a visible, specific test failure instead of
// silently passing a count check.
//
// ── Ground truth ──────────────────────────────────────────────────────────
// Expected strings below were generated by running the REAL JS builder via
// node against fixtures/comprehensive.vcf, using the same `loadBrowserClasses`
// / `VCardAdapter` helpers the JS test suite uses (test/helpers/load-app.js).
// Generator script (saved for reproducibility — rerun after any relationship-
// builder.js change to confirm the fixtures below still reflect JS behavior):
//
//   node --input-type=module -e '
